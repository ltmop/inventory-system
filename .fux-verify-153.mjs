import { chromium } from 'playwright'
const TOKEN = process.argv[2]
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const ctx = await browser.newContext({ viewport:{width:412,height:900}, deviceScaleFactor:2, isMobile:true, hasTouch:true, locale:'zh-CN' })
await ctx.addInitScript((t)=>{try{localStorage.setItem('fi-server','https://app.junchengzn.com');localStorage.setItem('fi-mobile-token',t);localStorage.setItem('fi-guided','1');localStorage.setItem('fi-operator','老板')}catch(e){}}, TOKEN)
const page = await ctx.newPage()
const errs=[]; page.on('pageerror', e=>errs.push(String(e.message).slice(0,120)))
await page.route('**/api/invoke**', async (route)=>{const req=route.request();try{const r=await fetch(req.url(),{method:req.method(),headers:{'Content-Type':'application/json'},body:req.postData()||undefined});await route.fulfill({status:r.status,contentType:'application/json',body:await r.text()})}catch(e){await route.fulfill({status:502,contentType:'application/json',body:'{"ok":false}'})}})
await page.goto('http://127.0.0.1:8099/?token='+TOKEN,{waitUntil:'networkidle',timeout:90000})
await page.waitForTimeout(3800)
await page.evaluate(()=>{location.hash='more'}); await page.waitForTimeout(2200)
const more = await page.evaluate(()=>document.getElementById('app').innerText.replace(/\n+/g,' | '))
console.log('【修④】更多页首屏: ' + more.slice(0,200))
console.log('【修④】还含 app.junchengzn.com ? ' + /app\.junchengzn\.com/.test(more) + '  还含「连接码接入」? ' + /连接码接入/.test(more))
console.log('【修②】还含 组合商品/配件清单 ? ' + /组合商品|配件清单/.test(more))
await page.evaluate(()=>{location.hash='stocktake'}); await page.waitForTimeout(2600)
console.log('【修③】核对货架: ' + (await page.evaluate(()=>document.getElementById('app').innerText.replace(/\n+/g,' | ').slice(0,240))))
await page.evaluate(()=>{location.hash='ai'}); await page.waitForTimeout(2200)
const ai = await page.evaluate(()=>document.getElementById('app').innerText.replace(/\n+/g,' | '))
console.log('【修④】AI 页: ' + ai.slice(0,120))
console.log('【修④】还含 doubao ? ' + /doubao/.test(ai))
await page.evaluate(()=>{location.hash='inbound'}); await page.waitForTimeout(2200)
const ib = await page.evaluate(()=>document.getElementById('app').innerText.replace(/\n+/g,' | '))
console.log('【修④】入库页: ' + ib.slice(0,110))
await page.evaluate(()=>{location.hash='specbatch'}); await page.waitForTimeout(2400)
const opts = await page.evaluate(()=>{const s=document.querySelector('#sb-cat'); return s?[...s.options].map(o=>o.text).slice(0,8):[]})
console.log('【修⑤】分类下拉前 8 项: ' + JSON.stringify(opts))
console.log('JS 报错: ' + (errs.length?errs.join(' | '):'(无)'))
await browser.close()